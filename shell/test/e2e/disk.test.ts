import assert from 'node:assert/strict'
import { it } from 'node:test'
import { launch, waitFor } from './harness.js'

it('disk warning opens an unsent cleanup draft, preserves edits, settings persist and RU/EN defaults follow language', async () => {
  const h = await launch({ name: 'disk', env: { PULT_LANG: '' } })
  try {
    assert.ok(await waitFor(async () => await h.win.getAttribute('.app', 'data-conn') === 'up', 20_000))
    const c = await h.client()
    await h.win.evaluate(async () => { await window.pult!.call('settings.set', { language: 'ru', disk: { thresholdGb: 999999, prompt: null } }) })
    await h.win.reload()
    const warning = h.win.getByTestId('disk-warning')
    await warning.waitFor()
    await h.win.getByTestId('disk-cleanup').click()
    const input = h.win.getByTestId('draft-input')
    await input.waitFor()
    assert.equal(await input.inputValue(), 'Помоги почистить диск')
    const draftCount = await h.win.getByTestId('draft-row').count()
    await h.win.getByTestId('disk-cleanup').dblclick()
    assert.equal(await h.win.getByTestId('draft-row').count(), draftCount, 'repeat click reuses the untouched draft')
    assert.equal((await c.request('agent.list') as { sessions: unknown[] }).sessions.length, 0, 'cleanup never sends')
    await input.fill('мой черновик')
    await h.win.getByTestId('disk-cleanup').click()
    assert.equal(await input.inputValue(), 'Помоги почистить диск')
    assert.equal(await h.win.getByTestId('draft-row').count(), draftCount + 1, 'edited draft is preserved separately')
    await h.screen('disk-warning-ru')
    await warning.getByRole('button', { name: 'Настройки хранения' }).click()
    await h.win.getByTestId('disk-threshold').fill('8')
    await h.win.getByTestId('disk-prompt').fill('My custom cleanup')
    await h.win.getByRole('button', { name: 'Сохранить настройки диска', exact: true }).click()
    assert.ok(await waitFor(async () => (await c.request('settings.get') as { disk: { settings: { prompt: string } } }).disk.settings.prompt === 'My custom cleanup', 5000))
    await h.screen('disk-settings-ru')
    await h.win.evaluate(async () => { await window.pult!.call('settings.set', { language: 'en', disk: { thresholdGb: 999999, prompt: 'My custom cleanup' } }) })
    await h.win.reload()
    await warning.waitFor()
    await h.win.getByTestId('disk-cleanup').click()
    assert.equal(await input.inputValue(), 'My custom cleanup')
    await h.win.evaluate(async () => { await window.pult!.call('settings.set', { disk: { thresholdGb: 999999, prompt: ' ' } }) })
    await h.win.reload()
    await warning.waitFor()
    await h.win.getByTestId('disk-cleanup').click()
    assert.equal(await input.inputValue(), 'Help me free up disk space')
    await h.win.setViewportSize({ width: 390, height: 844 })
    await h.screen('disk-warning-en-narrow')
    assert.ok(await h.win.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'no horizontal overflow')
    await h.win.setViewportSize({ width: 320, height: 700 })
    await warning.getByRole('button', { name: 'Storage settings' }).click()
    await h.win.getByTestId('disk-threshold').waitFor()
    await h.screen('disk-settings-en-narrow')
    assert.ok(await h.win.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'storage settings fit a narrow window')
    c.close()
  } finally { await h.close() }
})
